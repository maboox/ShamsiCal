"""Refresh cross-platform, hash-verified runtime pins from the tested environment.

Run only when intentionally updating dependencies. Hashes come directly from
PyPI release metadata, including all available wheels for each pinned version.
"""

import importlib.metadata as metadata
import json
import subprocess
import tomllib
from pathlib import Path

from packaging.requirements import Requirement
from packaging.utils import canonicalize_name

ROOT = Path(__file__).resolve().parents[1]
config = tomllib.loads((ROOT / "pyproject.toml").read_text())
queue = [Requirement(item).name for item in config["project"]["dependencies"]]
packages = {}
while queue:
    name = canonicalize_name(queue.pop())
    if name in packages:
        continue
    dist = metadata.distribution(name)
    packages[name] = dist.version
    for value in dist.requires or []:
        requirement = Requirement(value)
        if requirement.marker is None or requirement.marker.evaluate({"extra": ""}):
            queue.append(requirement.name)
lines = [
    "# Runtime lock for Python 3.11+. Generated by tools/lock_dependencies.py.",
    "# Install with: python -m pip install --require-hashes -r requirements.lock",
    "",
]
for name, version in sorted(packages.items()):
    response = subprocess.run(
        [
            "curl",
            "--ipv4",
            "--fail",
            "--silent",
            "--show-error",
            "--retry",
            "2",
            "--max-time",
            "40",
            f"https://pypi.org/pypi/{name}/{version}/json",
        ],
        check=True,
        capture_output=True,
    )
    release = json.loads(response.stdout)
    hashes = sorted({file["digests"]["sha256"] for file in release["urls"] if not file.get("yanked")})
    if not hashes:
        raise RuntimeError(f"No published files for {name}=={version}")
    lines.append(f"{name}=={version} \\")
    lines.extend(
        f"    --hash=sha256:{digest}" + (" \\" if index < len(hashes) - 1 else "")
        for index, digest in enumerate(hashes)
    )
    lines.append("")
(ROOT / "requirements.lock").write_text("\n".join(lines), encoding="utf-8")
print(f"Locked {len(packages)} runtime packages")
